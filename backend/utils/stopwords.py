# ==================== 合法词正则（复用 bilibili.py:1231）====================
# 只保留中文/字母/数字组合（≥2字），过滤纯标点/emoji/单字
WORD_PATTERN = re.compile(r'^[\u4e00-\u9fffa-zA-Z0-9]{2,}$')

# ==================== 预处理正则（借鉴 biliscope biliapi.js:107-120）====================
_URL_RE = re.compile(r'(?:https?|ftp)://[\S]+')
_DATE_RE = re.compile(r'\d{4}[-./]\d{1,2}([-./]\d{0,2})?(\s\d{2}:\d{2}:\d{2})?')
_AVID_RE = re.compile(r'[aA][vV]\d+')
_BVID_RE = re.compile(r'[bB][vV]1[1-9a-km-zA-HJ-NP-Z]{9}')
_PUNCT_RE = re.compile(r'[【】《》〖〗『』⚡！？…—\-_]')


def clean_text(text):
    """分词前预处理：去 URL/bvid/av号/日期/IGNORE_WORDS/常见标点。

    借鉴 biliscope biliapi.js updateWordMap 的清洗逻辑。
    返回清洗后的文本（可能含空格，供 jieba 分词）。
    """
    if not text:
        return ''
    # URL
    text = _URL_RE.sub('', text)
    # 日期（YYYY-MM-DD / YYYY-M-D / YYYY-MM 等）
    text = _DATE_RE.sub('', text)
    # avid（av123 / AV123）
    text = _AVID_RE.sub('', text)
    # bvid（BV1xxxxxxxxx）
    text = _BVID_RE.sub('', text)
    # IGNORE_WORDS 整词替换为空格（避免粘连，如"鬼畜调教"→" 调教"）
    for w in IGNORE_WORDS:
        text = text.replace(w, ' ')
    # 常见标点替换为空格
    text = _PUNCT_RE.sub(' ', text)
    return text


def clean_danmaku_text(text):
    """弹幕专用预处理。

    与标题 ``clean_text`` 的区别是：不删除“鬼畜/调教/剪辑”等内容词，
    这些词在弹幕语境中仍可能有意义；这里只清除格式噪声。
    """
    if not text:
        return ''
    text = _URL_RE.sub('', text)
    text = _DATE_RE.sub('', text)
    text = _AVID_RE.sub('', text)
    text = _BVID_RE.sub('', text)
    return _PUNCT_RE.sub(' ', text)


